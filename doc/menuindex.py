#!/usr/bin/env python3
# Index for the context-sensitive help in ML menu: menuindex.txt (written
# by lualatex, see ug-template-cam.tex) -> menuidx.dat, "NNN label" lines.
# menu_help_go_to_label (src/menuhelp.c) looks up the name of the selected
# menu entry there, ignoring case.
import os,sys

def write_menu_index(outdir = "cam", menu_header = True):
    try:
        f = open("menuindex.txt").readlines()
    except:
        print("Could not open menuindex.txt, will not rewrite help index files")
        raise SystemExit

    os.makedirs(outdir, exist_ok=True)
    # the camera splits this file at "\n" only
    o = open(os.path.join(outdir, "menuidx.dat"), "w", newline="\n")
    # entries for the old "Complete user guide" submenu (disabled in src/menuindex.c)
    menu = open("../src/menuindexentries.h", "w") if menu_header else open(os.devnull, "w")

    print("""
// Auto-generated; do not edit this file.
// Edit doc/menuindex.py instead.
""", file=menu)

    print("001 About Magic Lantern", file=o)

    sections = 0

    for l in f[1:]:
        l = l.strip("\n").split(" ")
        try: page, type, name = l[0], l[1], " ".join(l[2:])
        except:
            print(l)
        page = int(page)
        name = name.replace(r"$\leftrightarrow $", "<-->")
        name = name.replace(r"$\rightarrow $", "->")

        if type == "label": # \helplabel{...}: a menu entry name, as it is
            print("%03d %s" % (page, name.strip()), file=o)

        if type == "subsubsection": # each menu entry is a subsection
            item = name.split(":")[0]

            if " and " in item:
                and_terms = item.split(" and ")
                for t in and_terms:
                    print("%03d %s" % (page, t.strip()), file=o)
                continue

            item = item.split(" / ")[0]
            item = item.split(" (")[0]
            item = item.split(" X sec")[0]
            item = item.strip()
            print("%03d %s" % (page, item), file=o)

        if type == "section": # main sections in menu
            sections += 1
            item = name
            print("%03d %s" % (page, item), file=o)
            print("""    {
        .name = "%s",
        .priv = "%s",
        .select = menu_help_go_to_label,
        .update = user_guide_display,
        .icon_type = IT_ACTION,
    },""" % (item, item), file=menu)

        if type == "end":
            lastpage = page - 1
            print("%03d end" % lastpage, file=o)

    o.close()
    menu.close()

if __name__ == "__main__":
    write_menu_index()
